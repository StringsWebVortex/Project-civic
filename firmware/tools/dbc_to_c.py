#!/usr/bin/env python3
"""Generate a constant C signal table from opendbc Honda DBC sources.

Usage: dbc_to_c.py <main.dbc> <out.c>
The main file's  CM_ "IMPORT x.dbc";  lines are resolved from the same
directory (as the opendbc generator does); the main file's definitions
override imported ones with the same message id. COUNTER/CHECKSUM fields
are skipped (they carry no vehicle data).
"""
import os, re, sys

SG = re.compile(r'^\s*SG_\s+(\w+)\s*:\s*(\d+)\|(\d+)@([01])([+-])\s*\(([^,]+),([^)]+)\)\s*\[[^\]]*\]\s*"([^"]*)"')
BO = re.compile(r'^BO_\s+(\d+)\s+(\w+)\s*:\s*(\d+)')
VAL = re.compile(r'^VAL_\s+(\d+)\s+(\w+)\s+(.*);')

def parse(path, msgs, vals):
    cur = None
    for line in open(path, encoding='utf-8', errors='replace'):
        m = BO.match(line)
        if m:
            mid = int(m.group(1))
            cur = {'id': mid, 'name': m.group(2), 'dlc': int(m.group(3)), 'sigs': []}
            msgs[mid] = cur
            continue
        m = SG.match(line)
        if m and cur is not None:
            name = m.group(1)
            if name in ('COUNTER', 'CHECKSUM'):
                continue
            cur['sigs'].append({'name': name, 'start': int(m.group(2)), 'len': int(m.group(3)),
                                'le': m.group(4) == '1', 'signed': m.group(5) == '-',
                                'factor': float(m.group(6)), 'offset': float(m.group(7)), 'unit': m.group(8)})
            continue
        if not line.strip():
            cur = None
        m = VAL.match(line)
        if m:
            pairs = re.findall(r'(-?\d+)\s+"([^"]*)"', m.group(3))
            vals[(int(m.group(1)), m.group(2))] = [(int(v), t) for v, t in pairs]

def main():
    main_dbc, out = sys.argv[1], sys.argv[2]
    d = os.path.dirname(main_dbc)
    msgs, vals = {}, {}
    for imp in re.findall(r'CM_\s+"IMPORT\s+([\w.]+)"', open(main_dbc).read()):
        parse(os.path.join(d, imp), msgs, vals)
    parse(main_dbc, msgs, vals)
    msgs = [m for m in sorted(msgs.values(), key=lambda m: m['id']) if m['sigs'] and m['id'] <= 0x7FF]
    c = lambda s: s.replace('\\', '\\\\').replace('"', '\\"')
    o = ['/* generated by tools/dbc_to_c.py from %s - do not edit */' % os.path.basename(main_dbc),
         '#include "can_dbc.h"', '']
    o.append('static const can_dbc_val_t V[] = {')
    vref = {}
    n = 0
    for m in msgs:
        for s in m['sigs']:
            vl = vals.get((m['id'], s['name']))
            if vl:
                vref[(m['id'], s['name'])] = (n, len(vl))
                for v, t in vl:
                    o.append('  { %d, "%s" },' % (v, c(t)))
                    n += 1
    if n == 0:
        o.append('  { 0, "" },')
    o.append('};')
    o.append('static const can_dbc_sig_t S[] = {')
    sidx = []
    k = 0
    for m in msgs:
        sidx.append((k, len(m['sigs'])))
        for s in m['sigs']:
            vi, vn = vref.get((m['id'], s['name']), (0, 0))
            o.append('  { "%s", "%s", %d, %d, %d, %d, %.9g, %.9g, %d, %d },' % (
                s['name'], c(s['unit']), s['start'], s['len'], 1 if s['le'] else 0,
                1 if s['signed'] else 0, s['factor'], s['offset'], vi, vn))
            k += 1
    o.append('};')
    o.append('const can_dbc_msg_t can_dbc_msgs[] = {')
    for m, (si, sn) in zip(msgs, sidx):
        o.append('  { 0x%03X, "%s", %d, %d, &S[%d] },' % (m['id'], m['name'], m['dlc'], sn, si))
    o.append('};')
    o.append('const unsigned can_dbc_msg_count = %d;' % len(msgs))
    o.append('const can_dbc_val_t *const can_dbc_vals = V;')
    open(out, 'w').write('\n'.join(o) + '\n')

if __name__ == '__main__':
    main()
