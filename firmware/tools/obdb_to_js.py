#!/usr/bin/env python3
"""Embed the OBDb Honda Civic signal set (2013 model year) in web/index.html.

Usage: obdb_to_js.py <default.json> <index.html> [year]
Rewrites the block between  /*OBDB-BEGIN*/  and  /*OBDB-END*/  with
  const OBDB_SRC = "...";   const OBDB = [ {hdr,did,freq,sigs:[...]} , ... ];
Commands whose signals are all "Raw first byte" placeholders are kept with
sigs:[] so their raw replies are still requested and shown (nothing hidden).
Data: OBDb/Honda-Civic, CC BY-SA 4.0 (see firmware/obdb/LICENSE, SOURCE).
"""
import json, re, sys

def applies(f, y):
    if not f:
        return True
    return y in f.get('years', []) or ('to' in f and y <= f['to']) or ('from' in f and y >= f['from'])

def main():
    src, page = sys.argv[1], sys.argv[2]
    year = int(sys.argv[3]) if len(sys.argv) > 3 else 2013
    d = json.load(open(src))
    out = []
    for c in d['commands']:
        if not applies(c.get('filter') or c.get('dbgfilter'), year):
            continue
        svc, did = next(iter(c['cmd'].items()))
        if svc != '22':
            continue
        sigs = []
        for s in c.get('signals', []):
            if s['name'].startswith('Raw first byte'):
                continue
            f = s.get('fmt', {})
            e = {'id': s['id'], 'n': s['name'], 'p': s.get('path', ''), 'b': f.get('bix', 0), 'l': f.get('len', 8),
                 'u': f.get('unit', '')}
            for k_src, k in (('mul', 'm'), ('div', 'd'), ('add', 'a')):
                if k_src in f:
                    e[k] = f[k_src]
            if f.get('sign'):
                e['s'] = 1
            if 'map' in f:
                e['map'] = {str(k): (v.get('description', v.get('value', '')) if isinstance(v, dict) else v)
                            for k, v in f['map'].items()}
            sigs.append(e)
        out.append({'h': c['hdr'], 'r': c.get('rax', c['hdr'][2:]), 'did': did,
                    'f': c.get('freq', 1), 'sigs': sigs})
    origin = open(src.rsplit('/', 1)[0] + '/SOURCE').read().strip()
    block = ('/*OBDB-BEGIN*/\n/* generated by tools/obdb_to_js.py (%d model year) from %s, CC BY-SA 4.0 - do not edit */\n'
             'const OBDB_SRC=%s;\nconst OBDB=%s;\n/*OBDB-END*/') % (
        year, origin, json.dumps(origin), json.dumps(out, separators=(',', ':')))
    html = open(page, encoding='utf-8').read()
    if '/*OBDB-BEGIN*/' not in html:
        sys.exit('markers not found in ' + page)
    html = re.sub(r'/\*OBDB-BEGIN\*/.*?/\*OBDB-END\*/', lambda _: block, html, flags=re.S)
    open(page, 'w', encoding='utf-8').write(html)
    named = sum(len(x['sigs']) for x in out)
    print('%d commands (%d named signals, %d raw-only) embedded' % (len(out), named, sum(1 for x in out if not x['sigs'])))

if __name__ == '__main__':
    main()
